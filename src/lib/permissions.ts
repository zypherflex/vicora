export function effectivePermissions(
  orgType: OrgType,
  roles: readonly string[],
  grants: readonly string[] = [],
  revocations: readonly string[] = [],
): Set<Permission> {
  const caps = new Set(ORG_TYPE_CAPABILITIES[orgType]);
  const out = new Set<Permission>();
  for (const r of roles) for (const p of ROLE_PERMISSIONS[r as Role] ?? []) out.add(p);
  for (const g of grants) if ((PERMISSIONS as readonly string[]).includes(g)) out.add(g as Permission);
  for (const r of revocations) out.delete(r as Permission);
  for (const p of [...out]) if (!caps.has(p)) out.delete(p);
  return out;
}

